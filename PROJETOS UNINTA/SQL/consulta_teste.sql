/* Log de movimentações de folgas com saldo acumulado (banco único de dias).
   Parâmetro: :CHAPA (ex.: '04788') */
WITH MOVIMENTOS AS (
    SELECT
        ZMDFOLGAS.IDFOLGAS,
        ZMDFOLGAS.CODCOLIGADA,
        ZMDFOLGAS.CHAPA,
        PFUNC.NOME                                              AS NOMECOL,
        ZMDFOLGAS.DATASERVICO,
        ZMDFOLGAS.QTD,
        ZMDFOLGAS.CREDITODEBITO,
        CASE WHEN ZMDFOLGAS.CREDITODEBITO = 'C'
             THEN  ZMDFOLGAS.QTD
             ELSE -ZMDFOLGAS.QTD
        END                                                     AS MOVIMENTO
    FROM ZMDFOLGAS WITH (NOLOCK)
    JOIN PFUNC WITH (NOLOCK)
        ON PFUNC.CODCOLIGADA = ZMDFOLGAS.CODCOLIGADA
       AND PFUNC.CHAPA       = ZMDFOLGAS.CHAPA
    WHERE ZMDFOLGAS.CODCOLIGADA = 1
      AND ZMDFOLGAS.CHAPA       = :CHAPA
)
SELECT
    MOVIMENTOS.NOMECOL,
    MOVIMENTOS.DATASERVICO,
    MOVIMENTOS.QTD,
    MOVIMENTOS.CREDITODEBITO,
    SUM(MOVIMENTOS.MOVIMENTO) OVER (
        PARTITION BY MOVIMENTOS.CODCOLIGADA,
                     MOVIMENTOS.CHAPA
        ORDER BY     MOVIMENTOS.DATASERVICO,
                     MOVIMENTOS.IDFOLGAS
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    )                                                           AS SALDO_ACUMULADO,
    CASE
        WHEN SUM(MOVIMENTOS.MOVIMENTO) OVER (
             PARTITION BY MOVIMENTOS.CODCOLIGADA,
                          MOVIMENTOS.CHAPA
             ORDER BY     MOVIMENTOS.DATASERVICO,
                          MOVIMENTOS.IDFOLGAS
             ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
        ) < 0 THEN 'SALDO NEGATIVO'
    END                                                         AS ALERTA
FROM MOVIMENTOS
ORDER BY MOVIMENTOS.DATASERVICO,
         MOVIMENTOS.IDFOLGAS;

