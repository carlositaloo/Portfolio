-- Calcula percentuais e totais de aprovação, reprovação por nota e por falta,
-- agrupados por curso e período letivo.
-- A subconsulta calcula os índices por IDTURMADISC; a consulta externa agrega por curso.
-- Usa parâmetros :$CODCOLIGADA, :PERIODOLETIVO e :$CODTIPOCURSO.
SELECT
    TA.CURSO,
    TA.PERIODOLETIVO,
    CONVERT(DECIMAL(18, 2), AVG(TA.PORC_APROV))                                               AS MEDIA_PERC_APROV,
    CONVERT(DECIMAL(18, 2), AVG(TA.PORC_REPROV))                                              AS MEDIA_PERC_REPROV_NOTAS,
    CONVERT(DECIMAL(18, 2), AVG(TA.PORC_REPROV_FALTA))                                        AS MEDIA_PERC_REPROV_FALTAS,
    CONVERT(DECIMAL(18, 2), AVG(TA.PORC_REPROV_FALTA) + AVG(TA.PORC_REPROV))                 AS MEDIA_PERC_REPROV_TOTAL,
    CONVERT(DECIMAL(18, 2), 100 - AVG(TA.PORC_APROV) - AVG(TA.PORC_REPROV) - AVG(TA.PORC_REPROV_FALTA)) AS OUTROS,
    SUM(TA.ABS_APROV)                                                                         AS TOTAL_APROVADOS,
    SUM(TA.ABS_REPROV)                                                                        AS TOTAL_REPROVADOS_NOTA,
    SUM(TA.ABS_REPROV_FALTA)                                                                  AS TOTAL_REPROVADOS_FALTA,
    SUM(TA.ABS_REPROV + TA.ABS_REPROV_FALTA)                                                  AS TOTAL_REPROVADOS,
    SUM(TA.OUTROS)                                                                            AS TOTAL_OUTROS,
    SUM(TA.TOTAL)                                                                             AS TOTAL_GERAL
FROM (
    SELECT
        STD.IDTURMADISC,
        SP.CODPERLET  AS PERIODOLETIVO,
        SC.NOME       AS CURSO,
        SD.NOME       AS DISCIPLINA,
        ROUND(CAST(
            (SELECT 10000 * COUNT(SM.RA) FROM SMATRICULA SM (NOLOCK)
             WHERE SM.IDTURMADISC = STD.IDTURMADISC AND SM.CODCOLIGADA = STD.CODCOLIGADA AND SM.CODSTATUS = 10)
            / NULLIF((SELECT COUNT(*) FROM SMATRICULA SM2 (NOLOCK)
                      WHERE SM2.IDTURMADISC = STD.IDTURMADISC AND SM2.CODCOLIGADA = STD.CODCOLIGADA), 0)
        AS DECIMAL(9, 4)) / 100, 2) AS PORC_REPROV,
        (SELECT COUNT(SM.RA) FROM SMATRICULA SM (NOLOCK)
         WHERE SM.IDTURMADISC = STD.IDTURMADISC AND SM.CODCOLIGADA = STD.CODCOLIGADA AND SM.CODSTATUS = 10) AS ABS_REPROV,
        ROUND(CAST(
            (SELECT 10000 * COUNT(SM.RA) FROM SMATRICULA SM (NOLOCK)
             WHERE SM.IDTURMADISC = STD.IDTURMADISC AND SM.CODCOLIGADA = STD.CODCOLIGADA AND SM.CODSTATUS = 4319)
            / NULLIF((SELECT COUNT(*) FROM SMATRICULA SM2 (NOLOCK)
                      WHERE SM2.IDTURMADISC = STD.IDTURMADISC AND SM2.CODCOLIGADA = STD.CODCOLIGADA), 0)
        AS DECIMAL(9, 4)) / 100, 2) AS PORC_REPROV_FALTA,
        (SELECT COUNT(SM.RA) FROM SMATRICULA SM (NOLOCK)
         WHERE SM.IDTURMADISC = STD.IDTURMADISC AND SM.CODCOLIGADA = STD.CODCOLIGADA AND SM.CODSTATUS = 4319) AS ABS_REPROV_FALTA,
        ROUND(CAST(
            (SELECT 10000 * COUNT(SM.RA) FROM SMATRICULA SM (NOLOCK)
             WHERE SM.IDTURMADISC = STD.IDTURMADISC AND SM.CODCOLIGADA = STD.CODCOLIGADA AND SM.CODSTATUS = 1)
            / NULLIF((SELECT COUNT(RA) FROM SMATRICULA SM2 (NOLOCK)
                      WHERE SM2.IDTURMADISC = STD.IDTURMADISC AND SM2.CODCOLIGADA = STD.CODCOLIGADA), 0)
        AS DECIMAL(9, 4)) / 100, 2) AS PORC_APROV,
        (SELECT COUNT(SM.RA) FROM SMATRICULA SM (NOLOCK)
         WHERE SM.IDTURMADISC = STD.IDTURMADISC AND SM.CODCOLIGADA = STD.CODCOLIGADA AND SM.CODSTATUS = 1) AS ABS_APROV,
        (SELECT COUNT(SM.RA) FROM SMATRICULA SM (NOLOCK)
         WHERE SM.IDTURMADISC = STD.IDTURMADISC AND SM.CODCOLIGADA = STD.CODCOLIGADA
           AND SM.CODSTATUS NOT IN (1, 10, 4319)) AS OUTROS,
        (SELECT COUNT(*) FROM SMATRICULA SM2 (NOLOCK)
         WHERE SM2.IDTURMADISC = STD.IDTURMADISC AND SM2.CODCOLIGADA = STD.CODCOLIGADA) AS TOTAL
    FROM STURMADISC STD (NOLOCK)
        JOIN SDISCIPLINA SD (NOLOCK)
            ON STD.CODCOLIGADA = SD.CODCOLIGADA
           AND STD.CODDISC     = SD.CODDISC
        JOIN SPLETIVO SP (NOLOCK)
            ON SP.CODCOLIGADA = STD.CODCOLIGADA
           AND SP.IDPERLET    = STD.IDPERLET
        JOIN SHABILITACAOFILIAL SHAF (NOLOCK)
            ON SHAF.CODCOLIGADA          = STD.CODCOLIGADA
           AND SHAF.IDHABILITACAOFILIAL  = STD.IDHABILITACAOFILIAL
        JOIN SCURSO SC (NOLOCK)
            ON SC.CODCOLIGADA = SHAF.CODCOLIGADA
           AND SC.CODCURSO    = SHAF.CODCURSO
    WHERE SP.CODCOLIGADA   = :$CODCOLIGADA
      AND SP.CODPERLET     = :PERIODOLETIVO
      AND SC.CODTIPOCURSO  = :$CODTIPOCURSO
) AS TA
GROUP BY TA.CURSO, TA.PERIODOLETIVO
ORDER BY TA.CURSO;


