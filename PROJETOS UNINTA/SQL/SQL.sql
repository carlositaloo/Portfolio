        WHEN 181 THEN 'Desistência Formalizada'
        WHEN 59  THEN 'Desistência Formalizada'
        WHEN 183 THEN 'Transferência Externa'
        WHEN 49  THEN 'Transferência Externa'
        WHEN 182 THEN 'Matrícula Institucional'
        WHEN 60  THEN 'Matrícula Institucional'
        WHEN 82  THEN 'Transferência Interna'
