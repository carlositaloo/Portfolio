-- Gera sugestão de e-mail institucional (@discentes.uninta.edu.br) para alunos
-- ativos em cursos presenciais, no período letivo informado pelo parâmetro :CODPERLET.
-- Regras:
--   • Se o aluno tiver nome social, o primeiro nome do nome social é usado no e-mail.
--   • O "Nome de exibição" combina o primeiro nome (social ou civil) + último sobrenome.
--   • Formato do e-mail: primeirnome.RA@discentes.uninta.edu.br
SELECT
	DISTINCT
	CASE /*RETORNA SUGESTÃO DE E-MAIL INSTITUCIONAL, CASO A PESSOA POSSUA UM NOME SOCIAL O NOME SOCIAL É UTILIZADO NA COMPOSIÇÃO DO E-MAIL*/
		WHEN PPESSOA.NOMESOCIAL IS NOT NULL THEN SUBSTRING(PPESSOA.NOMESOCIAL, 1, CHARINDEX(' ', PPESSOA.NOMESOCIAL + ' ') - 1) + '.' + SALUNO.RA + '@discentes.uninta.edu.br'
		ELSE SUBSTRING(PPESSOA.NOME, 1, CHARINDEX(' ', PPESSOA.NOME + ' ') - 1) + '.' + SALUNO.RA + '@discentes.uninta.edu.br'		
	END AS [Nome de usuário],
	SUBSTRING(PPESSOA.NOME, 1, CHARINDEX(' ', PPESSOA.NOME + ' ') - 1) AS [Nome],
	RIGHT(LTRIM(RTRIM(PPESSOA.NOME)),
      CHARINDEX(' ', REVERSE(LTRIM(RTRIM(PPESSOA.NOME))) + ' ') - 1) AS [Sobrenome],
	COALESCE(
    NULLIF(SUBSTRING(LTRIM(RTRIM(PPESSOA.NOMESOCIAL)), 1,
      CHARINDEX(' ', LTRIM(RTRIM(PPESSOA.NOMESOCIAL)) + ' ') - 1), ''),
    SUBSTRING(LTRIM(RTRIM(PPESSOA.NOME)), 1,
      CHARINDEX(' ', LTRIM(RTRIM(PPESSOA.NOME)) + ' ') - 1)) + ' ' + RIGHT(LTRIM(RTRIM(PPESSOA.NOME)),
      CHARINDEX(' ', REVERSE(LTRIM(RTRIM(PPESSOA.NOME))) + ' ') - 1) 
      AS [Nome de exibição],
	'DISCENTE' AS Cargo,
	'UNINTA' AS Departamento,
	'' AS [Número comercial],
	'' AS [Telefone comercial],
	'' AS [Celular],
	'' AS [Fax],
	'' AS [Endereço de email alternativo],
	'' AS [Endereço],
	'' AS [Cidade],
	'' AS [Estado ou província],
	'' AS [CEP],
	'' AS [País ou região]
FROM HATENDIMENTOBASE WITH (NOLOCK)
JOIN HCLIENTEATENDIMENTO WITH (NOLOCK)
	ON HCLIENTEATENDIMENTO.CODCOLIGADA = HATENDIMENTOBASE.CODCOLIGADA
		AND HCLIENTEATENDIMENTO.CODLOCAL = HATENDIMENTOBASE.CODCOLIGADA
		AND HCLIENTEATENDIMENTO.CODATENDIMENTO = HATENDIMENTOBASE.CODATENDIMENTO
JOIN SALUNO WITH (NOLOCK)
	ON SALUNO.CODCOLIGADA = HCLIENTEATENDIMENTO.CODCOLIGADA
		AND SALUNO.RA = HCLIENTEATENDIMENTO.RAALUNO 
JOIN PPESSOA WITH (NOLOCK)
	ON PPESSOA.CODIGO = SALUNO.CODPESSOA
JOIN SHABILITACAOALUNO WITH (NOLOCK)
		ON SHABILITACAOALUNO.CODCOLIGADA = SALUNO.CODCOLIGADA
			AND SHABILITACAOALUNO.RA = SALUNO.RA
	JOIN SHABILITACAOFILIAL WITH (NOLOCK)
		ON SHABILITACAOFILIAL.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA
			AND SHABILITACAOFILIAL.IDHABILITACAOFILIAL = SHABILITACAOALUNO.IDHABILITACAOFILIAL 
	JOIN SMATRICPL WITH (NOLOCK)
		ON SMATRICPL.CODCOLIGADA = SALUNO.CODCOLIGADA
	 		AND SMATRICPL.RA = SALUNO.RA
	JOIN SPLETIVO WITH (NOLOCK)
		ON SPLETIVO.CODCOLIGADA = SMATRICPL.CODCOLIGADA
			AND SPLETIVO.IDPERLET = SMATRICPL.IDPERLET
	JOIN SCURSO WITH (NOLOCK)
		ON SCURSO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA
