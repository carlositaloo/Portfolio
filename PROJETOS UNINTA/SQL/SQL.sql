       AND HATENDIMENTOBASE.CODATENDIMENTO = HPARAMATENDIMENTO.CODATENDIMENTO
       AND HPARAMATENDIMENTO.CODPARAMETRO IN (61, 63, 65, 67, 282)
    JOIN SATENDIMENTO WITH (NOLOCK)
        ON SATENDIMENTO.CODCOLIGADA    = HATENDIMENTOBASE.CODCOLIGADA
       AND SATENDIMENTO.CODATENDIMENTO = HATENDIMENTOBASE.CODATENDIMENTO
       AND SATENDIMENTO.CODLOCAL       = HATENDIMENTOBASE.CODLOCAL
    JOIN SALUNO WITH (NOLOCK)
        ON SALUNO.CODCOLIGADA = SATENDIMENTO.CODCOLIGADA
       AND SALUNO.RA          = SATENDIMENTO.RA
    JOIN SHABILITACAOFILIAL WITH (NOLOCK)
        ON SHABILITACAOFILIAL.CODCOLIGADA         = SATENDIMENTO.CODCOLIGADA
       AND SHABILITACAOFILIAL.IDHABILITACAOFILIAL  = SATENDIMENTO.IDHABILITACAOFILIAL
    JOIN SCURSO WITH (NOLOCK)
        ON SCURSO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA
       AND SCURSO.CODCURSO    = SHABILITACAOFILIAL.CODCURSO
    JOIN SPLETIVO WITH (NOLOCK)
        ON SPLETIVO.CODCOLIGADA = SATENDIMENTO.CODCOLIGADA
       AND SPLETIVO.IDPERLET   = SATENDIMENTO.IDPERLET
    JOIN PPESSOA WITH (NOLOCK)
        ON PPESSOA.CODIGO = SALUNO.CODPESSOA
    JOIN STIPOCURSO WITH (NOLOCK)
        ON STIPOCURSO.CODCOLIGADA  = SALUNO.CODCOLIGADA
       AND STIPOCURSO.CODTIPOCURSO = SALUNO.CODTIPOCURSO
    JOIN HSOLICITACAO WITH (NOLOCK)
