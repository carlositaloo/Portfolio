/* ============================================================================
   CONSULTA DE FILTRO PARA TOTVS
   PESQUISA TURMAS/DISCIPINAS POR USUARIO
============================================================================ */
SELECT STURMADISC.IDTURMADISC
FROM   STURMADISC WITH (NOLOCK)
       LEFT JOIN SHABILITACAOFILIAL WITH (NOLOCK)
              ON SHABILITACAOFILIAL.CODCOLIGADA         = STURMADISC.CODCOLIGADA
             AND SHABILITACAOFILIAL.IDHABILITACAOFILIAL = STURMADISC.IDHABILITACAOFILIAL
       LEFT JOIN SCURSO WITH (NOLOCK)
              ON SCURSO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA
             AND SCURSO.CODCURSO    = SHABILITACAOFILIAL.CODCURSO
       LEFT JOIN STURMA WITH (NOLOCK)
              ON STURMA.CODCOLIGADA = STURMADISC.CODCOLIGADA
             AND STURMA.CODFILIAL   = STURMADISC.CODFILIAL
             AND STURMA.CODTURMA    = STURMADISC.CODTURMA
             AND STURMA.IDPERLET    = STURMADISC.IDPERLET
       LEFT JOIN SDISCIPLINA WITH (NOLOCK)
              ON SDISCIPLINA.CODCOLIGADA = STURMADISC.CODCOLIGADA
             AND SDISCIPLINA.CODDISC     = STURMADISC.CODDISC
       LEFT JOIN SPLETIVO WITH (NOLOCK)
              ON SPLETIVO.CODCOLIGADA = STURMA.CODCOLIGADA
             AND SPLETIVO.IDPERLET    = STURMA.IDPERLET
       LEFT JOIN SHABILITACAO WITH (NOLOCK)
              ON SHABILITACAO.CODCOLIGADA    = SHABILITACAOFILIAL.CODCOLIGADA
             AND SHABILITACAO.CODCURSO       = SHABILITACAOFILIAL.CODCURSO
             AND SHABILITACAO.CODHABILITACAO = SHABILITACAOFILIAL.CODHABILITACAO
       LEFT JOIN SDISCGRADE WITH (NOLOCK)
              ON SDISCGRADE.CODCOLIGADA    = SHABILITACAOFILIAL.CODCOLIGADA
             AND SDISCGRADE.CODCURSO       = SHABILITACAOFILIAL.CODCURSO
             AND SDISCGRADE.CODHABILITACAO = SHABILITACAOFILIAL.CODHABILITACAO
             AND SDISCGRADE.CODGRADE       = SHABILITACAOFILIAL.CODGRADE
             AND SDISCGRADE.CODDISC        = STURMADISC.CODDISC
WHERE  STURMADISC.CODFILIAL    = 1
  AND  STURMADISC.CODTIPOCURSO = :$CODTIPOCURSO
  AND  STURMADISC.CODCOLIGADA  = :$CODCOLIGADA
  AND  (
           -- Usuário é professor desta turma-disciplina
           EXISTS (
               SELECT 1
               FROM   SPROFESSORTURMA WITH (NOLOCK)
               JOIN   SPROFESSOR WITH (NOLOCK)
                   ON SPROFESSOR.CODCOLIGADA = SPROFESSORTURMA.CODCOLIGADA
                  AND SPROFESSOR.CODPROF     = SPROFESSORTURMA.CODPROF
               JOIN   PPESSOA WITH (NOLOCK)
                   ON PPESSOA.CODIGO = SPROFESSOR.CODPESSOA
               WHERE  SPROFESSORTURMA.CODCOLIGADA = STURMADISC.CODCOLIGADA
                 AND  SPROFESSORTURMA.IDTURMADISC  = STURMADISC.IDTURMADISC
                 AND  PPESSOA.CODUSUARIO           = :CODUSUARIO
           )
           OR
           -- Usuário é aluno matriculado nesta turma-disciplina
           EXISTS (
               SELECT 1
               FROM   SMATRICULA WITH (NOLOCK)
               JOIN   SALUNO WITH (NOLOCK)
                   ON SALUNO.CODCOLIGADA = SMATRICULA.CODCOLIGADA
                  AND SALUNO.RA          = SMATRICULA.RA
               JOIN   PPESSOA WITH (NOLOCK)
                   ON PPESSOA.CODIGO = SALUNO.CODPESSOA
               WHERE  SMATRICULA.CODCOLIGADA = STURMADISC.CODCOLIGADA
                 AND  SMATRICULA.IDTURMADISC  = STURMADISC.IDTURMADISC
                 AND  PPESSOA.CODUSUARIO      = :CODUSUARIO
           )
       );


/* ============================================================================
   PROFESSORES POR NÍVEL DE ENSINO (CODTIPOCURSO = 196)
   Retorna professores distintos que possuem turmas-disciplina vinculadas
   ao nível de ensino 196, na coligada 1.
============================================================================ */
SELECT DISTINCT
    SPROFESSOR.CODPROF          AS CODIGO_PROFESSOR,
    PPESSOA.NOME                AS NOME_PROFESSOR,
    PPESSOA.CPF,
    PPESSOA.EMAIL,
    PPESSOA.CODUSUARIO,
    STIPOCURSO.NOME             AS NIVEL_ENSINO
FROM SPROFESSORTURMA WITH (NOLOCK)
    JOIN SPROFESSOR WITH (NOLOCK)
        ON SPROFESSOR.CODCOLIGADA = SPROFESSORTURMA.CODCOLIGADA
       AND SPROFESSOR.CODPROF     = SPROFESSORTURMA.CODPROF
    JOIN PPESSOA WITH (NOLOCK)
        ON PPESSOA.CODIGO = SPROFESSOR.CODPESSOA
    JOIN STURMADISC WITH (NOLOCK)
        ON STURMADISC.CODCOLIGADA  = SPROFESSORTURMA.CODCOLIGADA
       AND STURMADISC.IDTURMADISC  = SPROFESSORTURMA.IDTURMADISC
    JOIN STIPOCURSO WITH (NOLOCK)
        ON STIPOCURSO.CODCOLIGADA  = STURMADISC.CODCOLIGADA
       AND STIPOCURSO.CODTIPOCURSO = STURMADISC.CODTIPOCURSO
WHERE SPROFESSORTURMA.CODCOLIGADA = 1
  AND STURMADISC.CODTIPOCURSO     = 1;


/*
MAPEAMENTO DE MODALIDADE (DIAGNOSTICO)
- Compara o que vem do polo do curso (SHABILITACAOFILIAL/STIPOCURSO/ZMDPOLOS)
- Compara o que vem da oferta da disciplina (STURMADISC.TIPO e STURMADISC.CODTIPOCURSO)
*/
SELECT TOP 200
          SALUNO.RA,
          PPESSOA.NOME AS NOMEALUNO,
          SPLETIVO.CODPERLET,
          SDISCIPLINA.CODDISC,
          SDISCIPLINA.NOME AS DISCIPLINA,
          STURMADISC.IDTURMADISC,
          STURMADISC.CODTURMA,
          STURMADISC.TIPO AS TIPO_STURMADISC,
          STURMADISC.CODTIPOCURSO AS CODTIPOCURSO_DISC,
          STIPOCURSODISC.NOME AS NOME_TIPOCURSO_DISC,
          ZMDPOLOSDISC.TIPOENSINO AS TIPOENSINO_DISC,
          ZMDPOLOSDISC.POLODIGITAL AS POLODIGITAL_DISC,
          SHABILITACAOFILIAL.CODTIPOCURSO AS CODTIPOCURSO_CURSO,
          STIPOCURSO.NOME AS NOME_TIPOCURSO_CURSO,
          ZMDPOLOS.TIPOENSINO AS TIPOENSINO_CURSO,
          ZMDPOLOS.POLODIGITAL AS POLODIGITAL_CURSO,
          CASE
                WHEN ISNULL(LTRIM(RTRIM(STURMADISC.TIPO)), '') = 'P' THEN 'Presencial'
                WHEN ISNULL(LTRIM(RTRIM(STURMADISC.TIPO)), '') = 'D' THEN 'Digital'
                WHEN ISNULL(LTRIM(RTRIM(STURMADISC.TIPO)), '') = 'E' THEN 'EAD'
                WHEN ISNULL(LTRIM(RTRIM(STURMADISC.TIPO)), '') = 'S' THEN 'Semipresencial'
                ELSE 'Nao informado'
          END AS MODALIDADE_POR_STURMADISC_TIPO,
          CASE
                WHEN ZMDPOLOSDISC.TIPOENSINO = 'P' THEN 'Presencial'
                WHEN ZMDPOLOSDISC.TIPOENSINO = 'E' AND ISNULL(ZMDPOLOSDISC.POLODIGITAL, 'N') = 'N' THEN 'Flex'
                WHEN ZMDPOLOSDISC.TIPOENSINO = 'E' AND ISNULL(ZMDPOLOSDISC.POLODIGITAL, 'N') = 'S' THEN 'Digital'
                WHEN ZMDPOLOSDISC.TIPOENSINO = 'S' THEN 'Semipresencial'
                ELSE 'Nao informado'
          END AS MODALIDADE_POR_POLO_DISC,
          CASE
                WHEN ZMDPOLOS.TIPOENSINO = 'P' THEN 'Presencial'
                WHEN ZMDPOLOS.TIPOENSINO = 'E' AND ISNULL(ZMDPOLOS.POLODIGITAL, 'N') = 'N' THEN 'Flex'
                WHEN ZMDPOLOS.TIPOENSINO = 'E' AND ISNULL(ZMDPOLOS.POLODIGITAL, 'N') = 'S' THEN 'Digital'
                WHEN ZMDPOLOS.TIPOENSINO = 'S' THEN 'Semipresencial'
                ELSE 'Nao informado'
          END AS MODALIDADE_POR_POLO_CURSO
FROM   SHABILITACAOALUNO WITH (NOLOCK)
          JOIN SALUNO WITH (NOLOCK)
             ON SALUNO.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA
                  AND SALUNO.RA = SHABILITACAOALUNO.RA
          JOIN PPESSOA WITH (NOLOCK)
             ON PPESSOA.CODIGO = SALUNO.CODPESSOA
          JOIN SHABILITACAOFILIAL WITH (NOLOCK)
             ON SHABILITACAOFILIAL.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA
                  AND SHABILITACAOFILIAL.IDHABILITACAOFILIAL = SHABILITACAOALUNO.IDHABILITACAOFILIAL
          JOIN STIPOCURSO WITH (NOLOCK)
             ON STIPOCURSO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA
                  AND STIPOCURSO.CODTIPOCURSO = SHABILITACAOFILIAL.CODTIPOCURSO
          LEFT JOIN ZMDPOLOS WITH (NOLOCK)
             ON ZMDPOLOS.CODCOLIGADA = STIPOCURSO.CODCOLIGADA
                  AND ZMDPOLOS.CODPOLO = STIPOCURSO.CODTIPOCURSO
          JOIN SMATRICPL WITH (NOLOCK)
             ON SMATRICPL.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA
                  AND SMATRICPL.RA = SHABILITACAOALUNO.RA
                  AND SMATRICPL.IDHABILITACAOFILIAL = SHABILITACAOALUNO.IDHABILITACAOFILIAL
          JOIN SPLETIVO WITH (NOLOCK)
             ON SPLETIVO.CODCOLIGADA = SMATRICPL.CODCOLIGADA
                  AND SPLETIVO.IDPERLET = SMATRICPL.IDPERLET
          JOIN SMATRICULA WITH (NOLOCK)
             ON SMATRICULA.CODCOLIGADA = SMATRICPL.CODCOLIGADA
                  AND SMATRICULA.RA = SMATRICPL.RA
                  AND SMATRICULA.IDPERLET = SMATRICPL.IDPERLET
                  AND SMATRICULA.IDHABILITACAOFILIAL = SMATRICPL.IDHABILITACAOFILIAL
          JOIN STURMADISC WITH (NOLOCK)
             ON STURMADISC.CODCOLIGADA = SMATRICULA.CODCOLIGADA
                  AND STURMADISC.IDTURMADISC = SMATRICULA.IDTURMADISC
          JOIN SDISCIPLINA WITH (NOLOCK)
             ON SDISCIPLINA.CODCOLIGADA = STURMADISC.CODCOLIGADA
                  AND SDISCIPLINA.CODDISC = STURMADISC.CODDISC
          LEFT JOIN STIPOCURSO STIPOCURSODISC WITH (NOLOCK)
             ON STIPOCURSODISC.CODCOLIGADA = STURMADISC.CODCOLIGADA
                  AND STIPOCURSODISC.CODTIPOCURSO = STURMADISC.CODTIPOCURSO
          LEFT JOIN ZMDPOLOS ZMDPOLOSDISC WITH (NOLOCK)
             ON ZMDPOLOSDISC.CODCOLIGADA = STIPOCURSODISC.CODCOLIGADA
                  AND ZMDPOLOSDISC.CODPOLO = STIPOCURSODISC.CODTIPOCURSO
WHERE  SHABILITACAOALUNO.CODCOLIGADA = :$CODCOLIGADA
          AND SHABILITACAOALUNO.RA = :RA
ORDER BY SPLETIVO.CODPERLET DESC,
             STURMADISC.CODTURMA,
             SDISCIPLINA.NOME;


