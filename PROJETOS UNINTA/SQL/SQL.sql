-- Busca nome, CPF, RA e situação de colaborador a partir do código de usuário.
-- Usa ROW_NUMBER para evitar duplicatas em caso de múltiplos vínculos em PFUNC
-- (prioriza situação 'A' = Ativo quando há mais de um registro).
SELECT
    PPESSOA.CODUSUARIO AS USUARIO,
    PPESSOA.NOME,
    PPESSOA.CPF,
    SALUNO.RA,
    PFUNC.CODSITUACAO  AS STATUS_COLABORADOR
FROM PPESSOA WITH (NOLOCK)
LEFT JOIN SALUNO WITH (NOLOCK)
    ON SALUNO.CODPESSOA = PPESSOA.CODIGO
LEFT JOIN (
    SELECT
        CODPESSOA,
        CODSITUACAO,
        ROW_NUMBER() OVER (
            PARTITION BY CODPESSOA
            ORDER BY CASE WHEN CODSITUACAO = 'A' THEN 0 ELSE 1 END
        ) AS RN
    FROM PFUNC WITH (NOLOCK)
) PFUNC
    ON PFUNC.CODPESSOA = PPESSOA.CODIGO
   AND PFUNC.RN = 1
WHERE PPESSOA.CODUSUARIO = '2022118497';
-- OU use: WHERE PPESSOA.CODUSUARIO LIKE '%parte_do_usuario%'


-- Busca nome, CPF, RA e indica se a pessoa é colaboradora (com status detalhado).
-- Observação: pode retornar duplicatas se houver múltiplos vínculos em PFUNC.
SELECT
    PPESSOA.CODUSUARIO AS USUARIO,
    PPESSOA.NOME,
    PPESSOA.CPF,
    SALUNO.RA,
    CASE WHEN PFUNC.CODPESSOA IS NOT NULL THEN 'SIM' ELSE 'NÃO' END AS COLABORADOR,
    PFUNC.CODSITUACAO AS STATUS_COLABORADOR,
    CASE
        WHEN PFUNC.CODSITUACAO = 'A' THEN 'ATIVO'
        WHEN PFUNC.CODSITUACAO IS NOT NULL THEN 'INATIVO'
        ELSE NULL
    END AS DESC_STATUS
FROM PPESSOA WITH (NOLOCK)
LEFT JOIN SALUNO WITH (NOLOCK)
    ON SALUNO.CODPESSOA = PPESSOA.CODIGO
LEFT JOIN PFUNC WITH (NOLOCK)
    ON PFUNC.CODPESSOA = PPESSOA.CODIGO
WHERE PPESSOA.CODUSUARIO = '1-03667';


-- Perfil completo de um usuário: verifica se é aluno e/ou colaborador, retornando
-- RA, seção/categoria e cargo do colaborador (quando houver).
-- Usa ROW_NUMBER para priorizar o vínculo ativo e subquery para garantir RA único.
-- Usa parâmetro :CODUSUARIO.
SELECT
    GUSUARIO.CODUSUARIO,
    PPESSOA.NOME,
    PPESSOA.CPF,
    CASE WHEN SALUNO_UNIQ.RA IS NOT NULL        THEN 'SIM' ELSE 'NÃO' END AS ALUNO,
    SALUNO_UNIQ.RA,
    CASE WHEN PFUNC_PRINCIPAL.CODPESSOA IS NOT NULL THEN 'SIM' ELSE 'NÃO' END AS COLABORADOR,
    CASE
        WHEN PFUNC_PRINCIPAL.CODSITUACAO = 'A' THEN 'ATIVO'
        WHEN PFUNC_PRINCIPAL.CODSITUACAO = 'D' THEN 'DEMITIDO'
        ELSE PFUNC_PRINCIPAL.CODSITUACAO
    END AS STATUS_COLABORADOR,
    PSECAO.DESCRICAO  AS CATEGORIA_COLABORADOR,
    PFUNCAO.NOME      AS CARGO
FROM GUSUARIO WITH (NOLOCK)
    JOIN PPESSOA WITH (NOLOCK)
        ON PPESSOA.CODUSUARIO = GUSUARIO.CODUSUARIO
    /* Verifica se é aluno (pega o primeiro RA para evitar duplicatas) */
    LEFT JOIN (
        SELECT CODPESSOA, MIN(RA) AS RA
        FROM SALUNO WITH (NOLOCK)
        WHERE CODCOLIGADA = 1
        GROUP BY CODPESSOA
    ) AS SALUNO_UNIQ
        ON SALUNO_UNIQ.CODPESSOA = PPESSOA.CODIGO
    /* Verifica se é colaborador (prioriza situação Ativa) */
    LEFT JOIN (
        SELECT
            CODPESSOA,
            CODCOLIGADA,
            CODSECAO,
            CODFUNCAO,
            CODSITUACAO,
            ROW_NUMBER() OVER (
                PARTITION BY CODPESSOA
                ORDER BY CASE WHEN CODSITUACAO = 'A' THEN 0 ELSE 1 END
            ) AS RN
        FROM PFUNC WITH (NOLOCK)
        WHERE CODCOLIGADA = 1
    ) AS PFUNC_PRINCIPAL
        ON PFUNC_PRINCIPAL.CODPESSOA = PPESSOA.CODIGO
       AND PFUNC_PRINCIPAL.RN = 1
    /* Seção/categoria do colaborador (ex: Professor, Serviços Gerais...) */
    LEFT JOIN PSECAO WITH (NOLOCK)
        ON PSECAO.CODCOLIGADA = PFUNC_PRINCIPAL.CODCOLIGADA
       AND PSECAO.CODIGO      = PFUNC_PRINCIPAL.CODSECAO
    /* Cargo do colaborador */
    LEFT JOIN PFUNCAO WITH (NOLOCK)
        ON PFUNCAO.CODCOLIGADA = PFUNC_PRINCIPAL.CODCOLIGADA
       AND PFUNCAO.CODIGO      = PFUNC_PRINCIPAL.CODFUNCAO
WHERE GUSUARIO.CODUSUARIO = :CODUSUARIO;


-- Perfil completo do usuário com verificação de acesso ao Portal do RH.
-- Retorna se o usuário é aluno e/ou colaborador, o cargo/seção e indica
-- permissões fun_web (portal) e fun_web_pto (ponto eletrônico).
-- Status COMPLETO = tem as duas permissões; INCOMPLETO = tem apenas uma.
-- Usa parâmetro :CODUSUARIO.
SELECT
    GUSUARIO.CODUSUARIO,
    PPESSOA.NOME,
    PPESSOA.CPF,
    CASE WHEN SALUNO_UNIQ.RA IS NOT NULL THEN 'SIM' ELSE 'NÃO' END AS ALUNO,
    SALUNO_UNIQ.RA,
    CASE WHEN PFUNC_PRINCIPAL.CODPESSOA IS NOT NULL THEN 'SIM' ELSE 'NÃO' END AS COLABORADOR,
    CASE
        WHEN PFUNC_PRINCIPAL.CODSITUACAO = 'A' THEN 'ATIVO'
        WHEN PFUNC_PRINCIPAL.CODSITUACAO = 'D' THEN 'DEMITIDO'
        ELSE PFUNC_PRINCIPAL.CODSITUACAO
    END AS STATUS_COLABORADOR,
    PSECAO.DESCRICAO AS CATEGORIA_COLABORADOR,
    PFUNCAO.NOME AS CARGO,
    /* fun_web = acesso ao portal; fun_web_pto = acesso ao ponto eletrônico */
    CASE WHEN ISNULL(PERMS_RH.TEM_FUN_WEB, 0)     = 1 THEN 'SIM' ELSE 'NÃO' END AS PERMISSAO_FUN_WEB,
    CASE WHEN ISNULL(PERMS_RH.TEM_FUN_WEB_PTO, 0) = 1 THEN 'SIM' ELSE 'NÃO' END AS PERMISSAO_FUN_WEB_PTO,
    CASE
        WHEN ISNULL(PERMS_RH.TEM_FUN_WEB, 0) = 1
         AND ISNULL(PERMS_RH.TEM_FUN_WEB_PTO, 0) = 1 THEN 'COMPLETO'
        WHEN ISNULL(PERMS_RH.TEM_FUN_WEB, 0) = 1
          OR ISNULL(PERMS_RH.TEM_FUN_WEB_PTO, 0) = 1 THEN 'INCOMPLETO'
        ELSE 'NÃO'
    END AS ACESSO_PORTAL_RH
FROM GUSUARIO WITH (NOLOCK)
    JOIN PPESSOA WITH (NOLOCK)
        ON PPESSOA.CODUSUARIO = GUSUARIO.CODUSUARIO
    LEFT JOIN (
        SELECT CODPESSOA, MIN(RA) AS RA
        FROM SALUNO WITH (NOLOCK)
        WHERE CODCOLIGADA = 1
        GROUP BY CODPESSOA
    ) AS SALUNO_UNIQ
        ON SALUNO_UNIQ.CODPESSOA = PPESSOA.CODIGO
    LEFT JOIN (
        SELECT
            CODPESSOA,
            CODCOLIGADA,
            CODSECAO,
            CODFUNCAO,
            CODSITUACAO,
            ROW_NUMBER() OVER (
                PARTITION BY CODPESSOA
                ORDER BY CASE WHEN CODSITUACAO = 'A' THEN 0 ELSE 1 END
            ) AS RN
        FROM PFUNC WITH (NOLOCK)
        WHERE CODCOLIGADA = 1
    ) AS PFUNC_PRINCIPAL
        ON PFUNC_PRINCIPAL.CODPESSOA = PPESSOA.CODIGO
       AND PFUNC_PRINCIPAL.RN = 1
    LEFT JOIN PSECAO WITH (NOLOCK)
        ON PSECAO.CODCOLIGADA = PFUNC_PRINCIPAL.CODCOLIGADA
       AND PSECAO.CODIGO      = PFUNC_PRINCIPAL.CODSECAO
    LEFT JOIN PFUNCAO WITH (NOLOCK)
        ON PFUNCAO.CODCOLIGADA = PFUNC_PRINCIPAL.CODCOLIGADA
       AND PFUNCAO.CODIGO      = PFUNC_PRINCIPAL.CODFUNCAO
    LEFT JOIN (
        SELECT
            CODUSUARIO,
            MAX(CASE WHEN CODPERFIL = 'fun_web'     THEN 1 ELSE 0 END) AS TEM_FUN_WEB,
            MAX(CASE WHEN CODPERFIL = 'fun_web_pto' THEN 1 ELSE 0 END) AS TEM_FUN_WEB_PTO
        FROM GUSRPERFIL WITH (NOLOCK)
        WHERE CODPERFIL IN ('fun_web', 'fun_web_pto')
        GROUP BY CODUSUARIO
    ) AS PERMS_RH
        ON PERMS_RH.CODUSUARIO = GUSUARIO.CODUSUARIO
WHERE GUSUARIO.CODUSUARIO = :CODUSUARIO;


