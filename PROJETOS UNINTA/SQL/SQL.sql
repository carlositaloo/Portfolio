-- Devedores com multa pendente, agrupados por unidade bibliográfica.
-- Retorna leitor, nome e valor total de multas em aberto por biblioteca.
-- LEMPRESTIMOS.CODCLIENTE → LUSUARIO.CODIGO → PPESSOA.CODIGO (nome do devedor).
SELECT
    ISNULL(LTRIM(RTRIM(LUNIDADE.UNIDADE)), 'Sem nome')        AS UNIDADE_BIBLIOTECARIA,
    LUSUARIO.CODIGO                                           AS COD_LEITOR,
    ISNULL(LTRIM(RTRIM(PPESSOA.NOME)), '—')                   AS NOME_DEVEDOR,
    COUNT(*)                                                  AS QTD_EMPRESTIMOS_COM_MULTA,
    CONVERT(DECIMAL(18,2), SUM(LEMP.VALORMULTA))              AS VALOR_TOTAL_MULTAS
FROM LUNIDADE WITH (NOLOCK)
JOIN LEMPRESTIMOS LEMP WITH (NOLOCK)
      ON LEMP.CODCOLIGADA = LUNIDADE.CODCOLIGADA
     AND LEMP.CODUNIDADE  = LUNIDADE.CODIGO
JOIN LUSUARIO WITH (NOLOCK)
      ON LUSUARIO.CODCOLIGADA = LEMP.CODCOLIGADA
     AND LUSUARIO.CODIGO      = LEMP.CODCLIENTE
LEFT JOIN PPESSOA WITH (NOLOCK)
       ON PPESSOA.CODIGO = LUSUARIO.CODPESSOA
WHERE LUNIDADE.CODCOLIGADA = 1
  AND ISNULL(LEMP.VALORMULTA, 0) > 0
GROUP BY
    LUNIDADE.CODCOLIGADA,
    LUNIDADE.CODIGO,
    LUNIDADE.UNIDADE,
    LUSUARIO.CODIGO,
    PPESSOA.NOME
ORDER BY
    VALOR_TOTAL_MULTAS DESC,
    LUNIDADE.UNIDADE,
    PPESSOA.NOME;


