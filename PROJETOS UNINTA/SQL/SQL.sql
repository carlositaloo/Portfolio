-- Bloqueio de duplicidade na criação de e-mail institucional.
-- Retorna mensagem de erro se o aluno já possui uma solicitação do tipo 686
-- em aberto. Usado como validação em formulário do portal.
-- Parâmetros de formulário: :FRM_CMP_COLI (coligada) e :FRM_CMP_RA (RA do aluno).
SELECT DADOS.CODCOLIGADA,
       DADOS.RA,
       CASE
           WHEN EXISTS (
               SELECT TOP 1 1
               FROM HATENDIMENTOBASE HB WITH (NOLOCK)
               JOIN SATENDIMENTO SA WITH (NOLOCK)
                 ON SA.CODCOLIGADA    = HB.CODCOLIGADA
                AND SA.CODLOCAL       = HB.CODLOCAL
                AND SA.CODATENDIMENTO = HB.CODATENDIMENTO
               WHERE SA.CODCOLIGADA        = DADOS.CODCOLIGADA
                 AND SA.RA                 = DADOS.RA
                 AND HB.CODTIPOATENDIMENTO = 686
                 /* Opcional: ignorar cancelados/indeferidos */
                 -- AND HB.CODTAREFA NOT IN (:TAREFA_CANCELADO, :TAREFA_INDEFERIDO)
           )
           THEN 'VOCÊ JÁ POSSUI SOLICITAÇÃO DE CRIAÇÃO DE E-MAIL. ACOMPANHE EM SOLICITAÇÕES.'
           ELSE ''
       END AS ERRO
FROM (
    SELECT :FRM_CMP_COLI AS CODCOLIGADA,
           :FRM_CMP_RA   AS RA
) DADOS;


