-- Lista os polos de atuação de um professor, incluindo indicador de permissão
-- de acesso ao polo (verifica via SUSUARIOFILIAL).
-- Usa parâmetros :$CODCOLIGADA e :CODPROF.
SELECT DISTINCT
    SPROFESSOR.CODPROF      AS CODIGO_PROFESSOR,
    PPESSOA.NOME            AS NOME_PROFESSOR,
    SCURSO.NOME             AS CURSO,
    SPLETIVO.CODPERLET,
    CONCAT(
        STIPOCURSO.CODTIPOCURSO, ' - ',
        STIPOCURSO.NOME,
        CASE WHEN ZMDPOLOS.CODINEP IS NOT NULL THEN CONCAT(' (', ZMDPOLOS.CODINEP, ')') END,
        CASE WHEN NOT EXISTS (
                SELECT 1
                FROM SUSUARIOFILIAL WITH (NOLOCK)
                WHERE SUSUARIOFILIAL.CODCOLIGADA  = SHABILITACAOFILIAL.CODCOLIGADA
                  AND SUSUARIOFILIAL.CODTIPOCURSO = SHABILITACAOFILIAL.CODTIPOCURSO
                  AND SUSUARIOFILIAL.CODFILIAL    = SHABILITACAOFILIAL.CODFILIAL
                  AND SUSUARIOFILIAL.CODUSUARIO   = PPESSOA.CODUSUARIO
             ) THEN ' SEM PERMISSÃO'
        END
    ) AS POLO
FROM SPROFESSOR WITH (NOLOCK)
    JOIN PPESSOA WITH (NOLOCK)
        ON PPESSOA.CODIGO = SPROFESSOR.CODPESSOA
    JOIN SPROFESSORTURMA WITH (NOLOCK)
        ON SPROFESSORTURMA.CODCOLIGADA = SPROFESSOR.CODCOLIGADA
       AND SPROFESSORTURMA.CODPROF     = SPROFESSOR.CODPROF
    JOIN STURMADISC WITH (NOLOCK)
        ON STURMADISC.CODCOLIGADA  = SPROFESSORTURMA.CODCOLIGADA
       AND STURMADISC.IDTURMADISC  = SPROFESSORTURMA.IDTURMADISC
    JOIN SHABILITACAOFILIAL WITH (NOLOCK)
        ON SHABILITACAOFILIAL.CODCOLIGADA         = STURMADISC.CODCOLIGADA
       AND SHABILITACAOFILIAL.IDHABILITACAOFILIAL  = STURMADISC.IDHABILITACAOFILIAL
    JOIN STIPOCURSO WITH (NOLOCK)
        ON STIPOCURSO.CODCOLIGADA  = SHABILITACAOFILIAL.CODCOLIGADA
       AND STIPOCURSO.CODTIPOCURSO = SHABILITACAOFILIAL.CODTIPOCURSO
    LEFT JOIN ZMDPOLOS WITH (NOLOCK)
        ON ZMDPOLOS.CODCOLIGADA = STIPOCURSO.CODCOLIGADA
       AND ZMDPOLOS.CODPOLO     = STIPOCURSO.CODTIPOCURSO
    JOIN SHABILITACAO WITH (NOLOCK)
        ON SHABILITACAO.CODCOLIGADA     = SHABILITACAOFILIAL.CODCOLIGADA
       AND SHABILITACAO.CODCURSO        = SHABILITACAOFILIAL.CODCURSO
       AND SHABILITACAO.CODHABILITACAO  = SHABILITACAOFILIAL.CODHABILITACAO
    JOIN SCURSO WITH (NOLOCK)
        ON SCURSO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA
       AND SCURSO.CODCURSO    = SHABILITACAOFILIAL.CODCURSO
    JOIN SPLETIVO WITH (NOLOCK)
        ON SPLETIVO.CODCOLIGADA = STURMADISC.CODCOLIGADA
       AND SPLETIVO.IDPERLET    = STURMADISC.IDPERLET
WHERE SPROFESSOR.CODCOLIGADA = :$CODCOLIGADA
  AND SPROFESSOR.CODPROF     = :CODPROF;


-- Lista as disciplinas, turmas e polos de um professor por período letivo.
-- Inclui nome da disciplina, da turma e status de permissão de acesso ao polo.
-- Usa parâmetros :$CODCOLIGADA e :CODPROF.
SELECT DISTINCT
    SPROFESSOR.CODPROF,
    PPESSOA.NOME,
    SCURSO.NOME             AS SCURSO,
    SPLETIVO.CODPERLET,
    SDISCIPLINA.NOME        AS DISCIPLINA,
    STURMA.NOME             AS TURMA,
    CONCAT(
        STIPOCURSO.CODTIPOCURSO, ' - ',
        STIPOCURSO.NOME,
        CASE WHEN ZMDPOLOS.CODINEP IS NOT NULL THEN CONCAT(' (', ZMDPOLOS.CODINEP, ')') END,
        CASE WHEN NOT EXISTS (
                SELECT 1
                FROM SUSUARIOFILIAL WITH (NOLOCK)
                WHERE SUSUARIOFILIAL.CODCOLIGADA  = SHABILITACAOFILIAL.CODCOLIGADA
                  AND SUSUARIOFILIAL.CODTIPOCURSO = SHABILITACAOFILIAL.CODTIPOCURSO
                  AND SUSUARIOFILIAL.CODFILIAL    = SHABILITACAOFILIAL.CODFILIAL
                  AND SUSUARIOFILIAL.CODUSUARIO   = PPESSOA.CODUSUARIO
             ) THEN ' SEM PERMISSÃO'
        END
    ) AS POLO
FROM SPROFESSOR WITH (NOLOCK)
    JOIN PPESSOA WITH (NOLOCK)
        ON PPESSOA.CODIGO = SPROFESSOR.CODPESSOA
    JOIN SPROFESSORTURMA WITH (NOLOCK)
        ON SPROFESSORTURMA.CODCOLIGADA = SPROFESSOR.CODCOLIGADA
       AND SPROFESSORTURMA.CODPROF     = SPROFESSOR.CODPROF
    JOIN STURMADISC WITH (NOLOCK)
        ON STURMADISC.CODCOLIGADA  = SPROFESSORTURMA.CODCOLIGADA
       AND STURMADISC.IDTURMADISC  = SPROFESSORTURMA.IDTURMADISC
    JOIN SHABILITACAOFILIAL WITH (NOLOCK)
        ON SHABILITACAOFILIAL.CODCOLIGADA         = STURMADISC.CODCOLIGADA
       AND SHABILITACAOFILIAL.IDHABILITACAOFILIAL  = STURMADISC.IDHABILITACAOFILIAL
    JOIN STIPOCURSO WITH (NOLOCK)
        ON STIPOCURSO.CODCOLIGADA  = SHABILITACAOFILIAL.CODCOLIGADA
       AND STIPOCURSO.CODTIPOCURSO = SHABILITACAOFILIAL.CODTIPOCURSO
    LEFT JOIN ZMDPOLOS WITH (NOLOCK)
        ON ZMDPOLOS.CODCOLIGADA = STIPOCURSO.CODCOLIGADA
       AND ZMDPOLOS.CODPOLO     = STIPOCURSO.CODTIPOCURSO
    JOIN SHABILITACAO WITH (NOLOCK)
        ON SHABILITACAO.CODCOLIGADA     = SHABILITACAOFILIAL.CODCOLIGADA
       AND SHABILITACAO.CODCURSO        = SHABILITACAOFILIAL.CODCURSO
       AND SHABILITACAO.CODHABILITACAO  = SHABILITACAOFILIAL.CODHABILITACAO
    JOIN SCURSO WITH (NOLOCK)
        ON SCURSO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA
       AND SCURSO.CODCURSO    = SHABILITACAOFILIAL.CODCURSO
    JOIN SDISCIPLINA WITH (NOLOCK)
        ON SDISCIPLINA.CODCOLIGADA = STURMADISC.CODCOLIGADA
       AND SDISCIPLINA.CODDISC     = STURMADISC.CODDISC
    JOIN STURMA WITH (NOLOCK)
        ON STURMA.CODCOLIGADA = STURMADISC.CODCOLIGADA
       AND STURMA.CODTURMA    = STURMADISC.CODTURMA
    JOIN SPLETIVO WITH (NOLOCK)
        ON SPLETIVO.CODCOLIGADA = STURMADISC.CODCOLIGADA
       AND SPLETIVO.IDPERLET    = STURMADISC.IDPERLET
WHERE SPROFESSOR.CODCOLIGADA = :$CODCOLIGADA
  AND SPROFESSOR.CODPROF     = :CODPROF;


