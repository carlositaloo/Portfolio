-- Alterações na turma-disciplina IDTURMADISC = 1495624.
-- Mostra apenas o que mudou (campo TIPO), quem alterou e quando,
-- comparando o registro 'O' (valor anterior) com 'U' (valor novo) via AUDITID.
SELECT
    U.AUDITID           AS ID_AUDITORIA,
    U.LOGUSER           AS USUARIO,
    U.RECMODIFIEDON     AS DATA_ALTERACAO,
    O.TIPO              AS TIPO_ANTERIOR,
    U.TIPO              AS TIPO_NOVO,
    U.CODTURMA          AS TURMA,
    U.CODDISC           AS DISCIPLINA,
    U.IDPERLET          AS PERIODO
FROM TOTVSAUDIT.STURMADISC U WITH (NOLOCK)
JOIN TOTVSAUDIT.STURMADISC O WITH (NOLOCK)
    ON  O.AUDITID     = U.AUDITID
    AND O.AUDITACTION = 'O'         -- O = valor ANTES da mudança
WHERE U.AUDITACTION = 'U'           -- U = valor DEPOIS da mudança
  AND U.CODCOLIGADA = 1
  AND U.IDTURMADISC = 1495624
ORDER BY U.RECMODIFIEDON;

