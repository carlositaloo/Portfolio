-- Dados completos do aluno: polo (com indicador de permissão), curso com código INEP,
-- turno, modalidade, tipo de ingresso, situação na habilitação e no período letivo.
-- Usa parâmetros :$CODCOLIGADA e :RA (compatível com relatórios TOTVS RM).
SELECT
    CONCAT(SALUNO.RA, ' - ', PPESSOA.NOME, ' (', PPESSOA.CPF, ')') AS [ALUNO(A)],
    SPLETIVO.IDPERLET,
    CONCAT(
        STIPOCURSO.CODTIPOCURSO, ' - ',
        STIPOCURSO.NOME,
        (CASE WHEN ZMDPOLOS.CODINEP IS NOT NULL THEN CONCAT(' (', ZMDPOLOS.CODINEP, ')') END),
        (CASE
            WHEN NOT EXISTS (
                SELECT 1
                FROM SUSUARIOFILIAL WITH (NOLOCK)
                WHERE SUSUARIOFILIAL.CODCOLIGADA  = SHABILITACAOFILIAL.CODCOLIGADA
                  AND SUSUARIOFILIAL.CODTIPOCURSO = SHABILITACAOFILIAL.CODTIPOCURSO
                  AND SUSUARIOFILIAL.CODFILIAL    = SHABILITACAOFILIAL.CODFILIAL
                  AND SUSUARIOFILIAL.CODUSUARIO   = PPESSOA.CODUSUARIO
            ) THEN ' SEM PERMISSÃO'
        END)
    ) AS POLO,
    CONCAT(
        SCURSO.NOME, ' (',
        (SELECT TOP 1 CODCURINEP
         FROM SCURSO A WITH (NOLOCK)
         WHERE A.CODCOLIGADA = SCURSO.CODCOLIGADA
           AND A.CODCURINEP IS NOT NULL
           AND (
               (STIPOCURSO.NOME LIKE 'POLO %SEMI%'        AND (A.COMPLEMENTO = SCURSO.COMPLEMENTO AND A.CODTIPOCURSO = 323))
               OR (STIPOCURSO.NOME LIKE 'POLO %' AND STIPOCURSO.NOME NOT LIKE '%SEMI%' AND (A.COMPLEMENTO = SCURSO.COMPLEMENTO AND A.CODTIPOCURSO = 4))
               OR (STIPOCURSO.NOME NOT LIKE 'POLO %'      AND A.CODCURSO = SCURSO.CODCURSO)
           )),
        ')'
    ) AS CURSO,
    SPLETIVO.CODPERLET          AS PERIODOLETIVO,
    STATUSPL.DESCRICAO          AS STATUSPERIODO,
    SMATRICPL.PERIODO,
    SHABILITACAOALUNO.IDHABILITACAOFILIAL,
    SHABILITACAOALUNO.IDHABILITACAOFILIALORIGEM,
    STATUSHAB.DESCRICAO         AS STATUSHAB,
    STURNO.NOME                 AS TURNO,
    (CASE
        WHEN ZMDPOLOS.TIPOENSINO = 'P'                                    THEN 'Presencial'
        WHEN ZMDPOLOS.TIPOENSINO = 'E' AND ISNULL(ZMDPOLOS.POLODIGITAL, 'N') = 'N' THEN 'Flex'
        WHEN ZMDPOLOS.TIPOENSINO = 'E' AND ISNULL(ZMDPOLOS.POLODIGITAL, 'N') = 'S' THEN 'Digital'
        WHEN ZMDPOLOS.TIPOENSINO = 'S'                                    THEN 'Semipresencial'
    END)                        AS MODALIDADE,
    STIPOINGRESSO.DESCRICAO     AS TIPOINGRESSO,
    SHABILITACAOALUNO.DTINGRESSO
FROM SHABILITACAOALUNO WITH (NOLOCK)
    /* Forma de ingresso */
    LEFT JOIN STIPOINGRESSO WITH (NOLOCK)
           ON STIPOINGRESSO.CODCOLIGADA       = SHABILITACAOALUNO.CODCOLIGADA
          AND STIPOINGRESSO.CODTIPOINGRESSO   = SHABILITACAOALUNO.CODTIPOINGRESSO
    /* Status na habilitação */
    JOIN SSTATUS STATUSHAB WITH (NOLOCK)
      ON STATUSHAB.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA
     AND STATUSHAB.CODSTATUS   = SHABILITACAOALUNO.CODSTATUS
    /* Aluno e pessoa */
    JOIN SALUNO WITH (NOLOCK)
         JOIN PPESSOA WITH (NOLOCK)
           ON PPESSOA.CODIGO = SALUNO.CODPESSOA
      ON SALUNO.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA
     AND SALUNO.RA          = SHABILITACAOALUNO.RA
    /* Curso */
    JOIN SHABILITACAOFILIAL WITH (NOLOCK)
         JOIN STURNO WITH (NOLOCK)
           ON STURNO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA
          AND STURNO.CODTURNO    = SHABILITACAOFILIAL.CODTURNO
         JOIN SCURSO WITH (NOLOCK)
           ON SCURSO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA
          AND SCURSO.CODCURSO    = SHABILITACAOFILIAL.CODCURSO
      ON SHABILITACAOFILIAL.CODCOLIGADA         = SHABILITACAOALUNO.CODCOLIGADA
     AND SHABILITACAOFILIAL.IDHABILITACAOFILIAL  = SHABILITACAOALUNO.IDHABILITACAOFILIAL
    /* Polo / nível de ensino */
    JOIN STIPOCURSO WITH (NOLOCK)
         LEFT JOIN ZMDPOLOS WITH (NOLOCK)
                ON ZMDPOLOS.CODCOLIGADA = STIPOCURSO.CODCOLIGADA
               AND ZMDPOLOS.CODPOLO     = STIPOCURSO.CODTIPOCURSO
      ON STIPOCURSO.CODCOLIGADA  = SHABILITACAOFILIAL.CODCOLIGADA
     AND STIPOCURSO.CODTIPOCURSO = SHABILITACAOFILIAL.CODTIPOCURSO
    /* Período letivo */
    LEFT JOIN SMATRICPL WITH (NOLOCK)
              JOIN SPLETIVO WITH (NOLOCK)
                ON SPLETIVO.CODCOLIGADA = SMATRICPL.CODCOLIGADA
               AND SPLETIVO.IDPERLET    = SMATRICPL.IDPERLET
              JOIN SSTATUS STATUSPL WITH (NOLOCK)
                ON STATUSPL.CODCOLIGADA = SMATRICPL.CODCOLIGADA
               AND STATUSPL.CODSTATUS   = SMATRICPL.CODSTATUS
      ON SMATRICPL.CODCOLIGADA          = SHABILITACAOALUNO.CODCOLIGADA
     AND SMATRICPL.IDHABILITACAOFILIAL  = SHABILITACAOALUNO.IDHABILITACAOFILIAL
     AND SMATRICPL.RA                   = SHABILITACAOALUNO.RA
WHERE SHABILITACAOALUNO.CODCOLIGADA = :$CODCOLIGADA
  AND SHABILITACAOALUNO.RA          = :RA;


