            WHEN ZMDPOLOS.TIPOENSINO = 'P' THEN 'Presencial'
            WHEN ZMDPOLOS.TIPOENSINO = 'E' AND ISNULL(ZMDPOLOS.POLODIGITAL, 'N') = 'N' THEN 'Flex'
            WHEN ZMDPOLOS.TIPOENSINO = 'E' AND ISNULL(ZMDPOLOS.POLODIGITAL, 'N') = 'S' THEN 'Digital'
            WHEN ZMDPOLOS.TIPOENSINO = 'S' THEN 'Semipresencial'
        END) AS MODALIDADE,
        STIPOINGRESSO.DESCRICAO AS TIPOINGRESSO,
        SHABILITACAOALUNO.DTINGRESSO
FROM    SHABILITACAOALUNO (NOLOCK)
        /* FORMA DE INGRESSO */
        LEFT JOIN STIPOINGRESSO (NOLOCK)
               ON STIPOINGRESSO.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA
                  AND STIPOINGRESSO.CODTIPOINGRESSO = SHABILITACAOALUNO.CODTIPOINGRESSO
        /* SITUAÇÃO NA MATRIZ APLICADA */
        JOIN SSTATUS STATUSHAB (NOLOCK)
          ON STATUSHAB.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA 
             AND STATUSHAB.CODSTATUS = SHABILITACAOALUNO.CODSTATUS
        /* ALUNO */
        JOIN SALUNO (NOLOCK)
             JOIN PPESSOA (NOLOCK)
               ON PPESSOA.CODIGO = SALUNO.CODPESSOA
          ON SALUNO.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA 
             AND SALUNO.RA = SHABILITACAOALUNO.RA
        /* CURSO */
        JOIN SHABILITACAOFILIAL (NOLOCK)
             JOIN STURNO (NOLOCK)
               ON STURNO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA 
                  AND STURNO.CODTURNO = SHABILITACAOFILIAL.CODTURNO 
             JOIN SCURSO (NOLOCK)
               ON SCURSO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA 
                  AND SCURSO.CODCURSO = SHABILITACAOFILIAL.CODCURSO
          ON SHABILITACAOFILIAL.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA 
             AND SHABILITACAOFILIAL.IDHABILITACAOFILIAL = SHABILITACAOALUNO.IDHABILITACAOFILIAL 
        /* NÍVEL DE ENSINO */
        JOIN STIPOCURSO (NOLOCK)
             LEFT JOIN ZMDPOLOS (NOLOCK)
                    ON ZMDPOLOS.CODCOLIGADA = STIPOCURSO.CODCOLIGADA 
                       AND ZMDPOLOS.CODPOLO = STIPOCURSO.CODTIPOCURSO 
              ON STIPOCURSO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA 
