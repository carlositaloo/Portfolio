    ON SALUNO.CODPESSOA = PPESSOA.CODIGO
WHERE PPESSOA.CODUSUARIO = '1-07337'


SELECT 
    PPESSOA.CODUSUARIO AS USUARIO,
    PPESSOA.NOME,
    PPESSOA.CPF,
    SALUNO.RA,
    CASE 
        WHEN PFUNC.CODPESSOA IS NOT NULL THEN 'SIM' 
        ELSE 'NÃO' 
    END AS COLABORADOR,
    PFUNC.CODSITUACAO AS STATUS_COLABORADOR,
    CASE 
        WHEN PFUNC.CODSITUACAO = 'A' THEN 'ATIVO' 
        WHEN PFUNC.CODSITUACAO IS NOT NULL THEN 'INATIVO'
        ELSE NULL
    END AS DESC_STATUS
FROM PPESSOA WITH (NOLOCK)
LEFT JOIN SALUNO WITH (NOLOCK)
    ON SALUNO.CODPESSOA = PPESSOA.CODIGO
LEFT JOIN PFUNC WITH (NOLOCK)
    ON PFUNC.CODPESSOA = PPESSOA.CODIGO
WHERE PPESSOA.CODUSUARIO = '1-03667'


/* ========================================================================== */
/* CONSULTA DE TURMAS/DISCIPLINAS DO ALUNO NO PERÍODO LETIVO MAIS ATUAL */
/* ========================================================================== */
SELECT  CONCAT(SALUNO.RA, ' - ', PPESSOA.NOME, ' (', PPESSOA.CPF, ')') AS [ALUNO(A)],
        SPLETIVO.IDPERLET,
        SPLETIVO.CODPERLET      AS PERIODOLETIVO,
        /* POLO */
        CONCAT(
            STIPOCURSO.CODTIPOCURSO, ' - ',
            STIPOCURSO.NOME, (CASE WHEN ZMDPOLOS.CODINEP IS NOT NULL THEN CONCAT(' (', ZMDPOLOS.CODINEP, ')') END),
            (CASE
                WHEN NOT EXISTS (
                    SELECT  1
                    FROM    SUSUARIOFILIAL (NOLOCK)
                    WHERE   SUSUARIOFILIAL.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA 
                            AND SUSUARIOFILIAL.CODTIPOCURSO = SHABILITACAOFILIAL.CODTIPOCURSO
                            AND SUSUARIOFILIAL.CODFILIAL = SHABILITACAOFILIAL.CODFILIAL 
                            AND SUSUARIOFILIAL.CODUSUARIO = PPESSOA.CODUSUARIO
                ) THEN ' SEM PERMISSÃO'
            END)
        ) AS POLO,
        /* CURSO */
        CONCAT(
             SCURSO.NOME, ' (',
             (SELECT TOP 1 CODCURINEP
             FROM    SCURSO A (NOLOCK)
             WHERE   A.CODCOLIGADA=SCURSO.CODCOLIGADA
                     AND A.CODCURINEP IS NOT NULL
                     AND (
                         (STIPOCURSO.NOME LIKE 'POLO %SEMI%' AND (A.COMPLEMENTO=SCURSO.COMPLEMENTO AND A.CODTIPOCURSO=323))
                         OR (STIPOCURSO.NOME LIKE 'POLO %' AND STIPOCURSO.NOME NOT LIKE '%SEMI%' AND (A.COMPLEMENTO=SCURSO.COMPLEMENTO AND A.CODTIPOCURSO=4))
                         OR (STIPOCURSO.NOME NOT LIKE 'POLO %' AND A.CODCURSO=SCURSO.CODCURSO)
                     )),
             ')'
        )                       AS CURSO,
        STATUSPL.DESCRICAO      AS STATUSPERIODO,
        SMATRICPL.PERIODO,
        SHABILITACAOALUNO.IDHABILITACAOFILIAL,
        SHABILITACAOALUNO.IDHABILITACAOFILIALORIGEM,
        STATUSHAB.DESCRICAO     AS STATUSHAB,
        STURNO.NOME AS TURNO,
        (CASE
            WHEN ZMDPOLOS.TIPOENSINO = 'P' THEN 'Presencial'
            WHEN ZMDPOLOS.TIPOENSINO = 'E' AND ISNULL(ZMDPOLOS.POLODIGITAL, 'N') = 'N' THEN 'Flex'
            WHEN ZMDPOLOS.TIPOENSINO = 'E' AND ISNULL(ZMDPOLOS.POLODIGITAL, 'N') = 'S' THEN 'Digital'
            WHEN ZMDPOLOS.TIPOENSINO = 'S' THEN 'Semipresencial'
        END) AS MODALIDADE,
        STIPOINGRESSO.DESCRICAO AS TIPOINGRESSO,
        SHABILITACAOALUNO.DTINGRESSO,
        /* INFORMAÇÕES DA DISCIPLINA */
        SDISCIPLINA.CODDISC,
        SDISCIPLINA.NOME        AS DISCIPLINA,
        SMATRICDISC.CODTURMADISC,
        STURMADISC.CODTURMA,
        STURMADISC.NUMTURMA,
        SMATRICDISC.CODSTATUSDISC,
        STATUSDISC.DESCRICAO    AS STATUSDISCIPLINA,
        SMATRICDISC.NOTA,
        SMATRICDISC.NOTAFINAL,
        SMATRICDISC.FALTA,
        SMATRICDISC.MEDIAAPROVACAO,
        SMATRICDISC.PERCFREQAPROV
FROM    SHABILITACAOALUNO (NOLOCK)
        /* FORMA DE INGRESSO */
        LEFT JOIN STIPOINGRESSO (NOLOCK)
               ON STIPOINGRESSO.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA
                  AND STIPOINGRESSO.CODTIPOINGRESSO = SHABILITACAOALUNO.CODTIPOINGRESSO
        /* SITUAÇÃO NA MATRIZ APLICADA */
        JOIN SSTATUS STATUSHAB (NOLOCK)
          ON STATUSHAB.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA 
             AND STATUSHAB.CODSTATUS = SHABILITACAOALUNO.CODSTATUS
        /* ALUNO */
        JOIN SALUNO (NOLOCK)
             JOIN PPESSOA (NOLOCK)
               ON PPESSOA.CODIGO = SALUNO.CODPESSOA
          ON SALUNO.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA 
             AND SALUNO.RA = SHABILITACAOALUNO.RA
        /* CURSO */
        JOIN SHABILITACAOFILIAL (NOLOCK)
             JOIN STURNO (NOLOCK)
               ON STURNO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA 
                  AND STURNO.CODTURNO = SHABILITACAOFILIAL.CODTURNO 
             JOIN SCURSO (NOLOCK)
               ON SCURSO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA 
                  AND SCURSO.CODCURSO = SHABILITACAOFILIAL.CODCURSO
          ON SHABILITACAOFILIAL.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA 
             AND SHABILITACAOFILIAL.IDHABILITACAOFILIAL = SHABILITACAOALUNO.IDHABILITACAOFILIAL 
        /* NÍVEL DE ENSINO */
        JOIN STIPOCURSO (NOLOCK)
             LEFT JOIN ZMDPOLOS (NOLOCK)
                    ON ZMDPOLOS.CODCOLIGADA = STIPOCURSO.CODCOLIGADA 
                       AND ZMDPOLOS.CODPOLO = STIPOCURSO.CODTIPOCURSO 
              ON STIPOCURSO.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA 
                 AND STIPOCURSO.CODTIPOCURSO = SHABILITACAOFILIAL.CODTIPOCURSO
        /* MATRÍCULA NO PERÍODO LETIVO MAIS ATUAL */
        JOIN SMATRICPL (NOLOCK) 
             JOIN SPLETIVO (NOLOCK)
               ON SPLETIVO.CODCOLIGADA = SMATRICPL.CODCOLIGADA 
                  AND SPLETIVO.IDPERLET = SMATRICPL.IDPERLET
             JOIN SSTATUS STATUSPL (NOLOCK)
               ON STATUSPL.CODCOLIGADA = SMATRICPL.CODCOLIGADA 
                  AND STATUSPL.CODSTATUS = SMATRICPL.CODSTATUS
          ON SMATRICPL.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA 
             AND SMATRICPL.IDHABILITACAOFILIAL = SHABILITACAOALUNO.IDHABILITACAOFILIAL 
             AND SMATRICPL.RA = SHABILITACAOALUNO.RA
             /* FILTRO PARA PEGAR O PERÍODO LETIVO MAIS ATUAL */
             AND SMATRICPL.IDPERLET = (
                 SELECT  TOP 1 IDPERLET
                 FROM    SMATRICPL MP (NOLOCK)
                 WHERE   MP.CODCOLIGADA = SHABILITACAOALUNO.CODCOLIGADA
                         AND MP.RA = SHABILITACAOALUNO.RA
                         AND MP.IDHABILITACAOFILIAL = SHABILITACAOALUNO.IDHABILITACAOFILIAL
                 ORDER BY MP.IDPERLET DESC
             )
        /* MATRÍCULA EM DISCIPLINAS */
        JOIN SMATRICDISC (NOLOCK)
             JOIN STURMADISC (NOLOCK)
                  JOIN SDISCIPLINA (NOLOCK)
                    ON SDISCIPLINA.CODCOLIGADA = STURMADISC.CODCOLIGADA
                       AND SDISCIPLINA.CODDISC = STURMADISC.CODDISC
               ON STURMADISC.CODCOLIGADA = SMATRICDISC.CODCOLIGADA
                  AND STURMADISC.IDTURMADISC = SMATRICDISC.IDTURMADISC
             JOIN SSTATUS STATUSDISC (NOLOCK)
               ON STATUSDISC.CODCOLIGADA = SMATRICDISC.CODCOLIGADA
                  AND STATUSDISC.CODSTATUS = SMATRICDISC.CODSTATUSDISC
          ON SMATRICDISC.CODCOLIGADA = SMATRICPL.CODCOLIGADA
             AND SMATRICDISC.IDPERLET = SMATRICPL.IDPERLET
             AND SMATRICDISC.RA = SMATRICPL.RA
             AND SMATRICDISC.IDHABILITACAOFILIAL = SMATRICPL.IDHABILITACAOFILIAL
WHERE   SHABILITACAOALUNO.CODCOLIGADA = :$CODCOLIGADA
        AND SHABILITACAOALUNO.RA = :RA
ORDER BY SDISCIPLINA.NOME

