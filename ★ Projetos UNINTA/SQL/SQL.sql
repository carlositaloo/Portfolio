            (CASE
                WHEN NOT EXISTS (
                    SELECT  1
                    FROM    SUSUARIOFILIAL (NOLOCK)
                    WHERE   SUSUARIOFILIAL.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA 
                            AND SUSUARIOFILIAL.CODTIPOCURSO = SHABILITACAOFILIAL.CODTIPOCURSO
